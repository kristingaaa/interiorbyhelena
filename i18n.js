const LANG_KEY = "ha-lang";
let currentLang = "sv";

/* Hämta text för nyckel i aktuellt språk, med svenska som reserv. */
function t(key, vars) {
  let s = (I18N[currentLang] && I18N[currentLang][key]) || I18N.sv[key] || key;
  if (vars) Object.keys(vars).forEach(k => { s = s.replace("{" + k + "}", vars[k]); });
  return s;
}

/* Byt språk utan sidladdning och uppdatera alla markerade element. */
function setLang(lang, persist) {
  if (!I18N[lang]) lang = "sv";
  currentLang = lang;
  document.documentElement.lang = lang;
  document.title = t("meta.title");
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute("content", t("meta.desc"));

  document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  // Endast egna, betrodda strängar från I18N används här
  document.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll("[data-i18n-attr]").forEach(el => {
    el.dataset.i18nAttr.split(";").forEach(pair => {
      const i = pair.indexOf(":");
      if (i > 0) el.setAttribute(pair.slice(0, i).trim(), t(pair.slice(i + 1).trim()));
    });
  });
  document.querySelectorAll(".lang button").forEach(b => {
    b.setAttribute("aria-pressed", String(b.dataset.lang === lang));
  });

  if (persist) { try { localStorage.setItem(LANG_KEY, lang); } catch (e) { /* ignoreras */ } }
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

/* Välj startspråk: sparat val, annars webbläsarens språk (sv om svenska, annars en). */
function initLang() {
  let lang = null;
  try { lang = localStorage.getItem(LANG_KEY); } catch (e) { /* ignoreras */ }
  if (!I18N[lang]) lang = (navigator.language || "").toLowerCase().startsWith("sv") ? "sv" : "en";
  setLang(lang, false);
}
